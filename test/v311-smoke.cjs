/** WEJI ARENA V3.1.1: manual entry of completed historical events, without LIVE. */
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const ts = (() => { try { return require("typescript"); } catch { return require("/opt/nvm/versions/node/v22.16.0/lib/node_modules/typescript"); } })();
const root = path.resolve(__dirname, "..");
const cache = {};
function load(file) {
  const resolved = path.resolve(root, file);
  if (cache[resolved]) return cache[resolved].exports;
  const m = new Module(resolved, module);
  cache[resolved] = m;
  m.filename = resolved;
  m.paths = Module._nodeModulePaths(path.dirname(resolved));
  m.require = (name) => name.startsWith("./") ? load(path.join(path.dirname(resolved), `${name}.ts`)) : require(name);
  m._compile(ts.transpileModule(fs.readFileSync(resolved, "utf8"), { fileName: resolved, compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText, resolved);
  return m.exports;
}
const { newEvent } = load("lib/arena-data.ts");
const { validArena } = load("lib/arena-storage.ts");
const { validHistoricalDate, validateHistoricalFinal } = load("lib/historical-entry.ts");
const { prepareSnapshot } = load("lib/score-integrity.ts");
const { validateMatchTransition } = load("lib/match-operations.ts");
const { calculateCatch } = load("lib/arena-rules.ts");
const { standings } = load("lib/arena-utils.ts");
const now = Date.UTC(2026, 10, 19, 7);
const participant = (id, squadId = null) => ({ id, name: id, username: id, squadId, checkedIn: true });
const snapshot = (event) => ({ version: 2, activeEventId: event.id, events: [event] });
const historic = newEvent("Galatama 18 November 2026", "solo");
historic.historical = true;
historic.location = "Planetary Observatory";
historic.eventDate = "2026-11-18";
historic.fish = [{ id: "f", name: "Blob Shark", points: 1, enabled: true }];
historic.bonuses = [{ id: "b", name: "Mutasi", points: 3, enabled: true }];
historic.participants = [participant("A"), participant("B"), participant("C")];
const initial = snapshot(historic);
assert.equal(validArena(initial), true);
assert.equal(validHistoricalDate("2026-11-18", now), true);
assert.equal(validHistoricalDate("2026-11-31", now), false);
assert.equal(validHistoricalDate("2026-11-20", now), false);
assert.equal(validHistoricalDate("2026-02-29", now), false);
assert.match(validateHistoricalFinal(historic, now), /Catat/);
const catchValue = calculateCatch(historic, "f", ["b"], 2);
const actualCatch = { id: "catch-a", participantId: "A", squadId: null, kind: "catch", delta: 8, description: "Blob ×2 + Mutasi", createdAt: "2026-11-18T13:00:00.000Z", fishId: "f", fishName: "Blob Shark", basePoints: 1, quantity: 2, bonuses: catchValue.bonuses, catchRef: "SS-001" };
const officialAdjustment = { id: "points-b", participantId: "B", squadId: null, kind: "manual", delta: 5, description: "Rekonsiliasi total poin resmi • arsip historis", createdAt: "2026-11-18T15:00:00.000Z" };
const officialThird = { ...officialAdjustment, id: "points-c", participantId: "C", delta: 2 };
const updated = structuredClone(historic);
updated.entries = [actualCatch, officialAdjustment, officialThird];
let result = prepareSnapshot(initial, snapshot(updated), now);
assert.equal(result.ok, true, JSON.stringify(result));
assert.equal(result.activity.length, 3);
assert.deepEqual(result.activity.map((item) => item.action), ["catch", "manual", "manual"]);
assert.equal(result.data.events[0].entries[0].createdAt, new Date(now).toISOString(), "server owns recording timestamp, not event timestamp");
const saved = result.data.events[0];
assert.equal(saved.status, "draft");
assert.equal(saved.startedAt, undefined);
assert.equal(saved.timer.runningSince, null);
assert.deepEqual(standings(saved).slice(0, 3).map((e) => e.points), [8, 5, 2]);
assert.equal(validateHistoricalFinal(saved, now), null);
const forgedLive = { ...saved, status: "live", timer: { ...saved.timer, runningSince: now } };
assert.match(prepareSnapshot(snapshot(saved), snapshot(forgedLive), now).error, /tidak boleh.*LIVE/i);
assert.match(validateMatchTransition(snapshot(saved), snapshot(forgedLive)), /status/i);
const tampered = structuredClone(saved);
tampered.entries[0].delta = 123;
assert.match(prepareSnapshot(snapshot(saved), snapshot(tampered), now).error, /tidak boleh diubah/i);
const dupRef = structuredClone(saved);
dupRef.entries.unshift({ ...actualCatch, id: "catch-2", catchRef: "ss-001" });
assert.match(prepareSnapshot(snapshot(saved), snapshot(dupRef), now).error, /Referensi/);
const wrongCalculation = structuredClone(saved);
wrongCalculation.entries.unshift({ ...actualCatch, id: "catch-wrong", catchRef: "SS-002", delta: 999 });
assert.match(prepareSnapshot(snapshot(saved), snapshot(wrongCalculation), now).error, /Poin tangkapan/);
const reversal = structuredClone(saved);
reversal.entries.unshift({ id: "reverse-a", participantId: "A", squadId: null, kind: "reversal", delta: -8, description: "Pembatalan", reversesEntryId: "catch-a", createdAt: "2026-11-18T14:00:00.000Z" });
assert.equal(prepareSnapshot(snapshot(saved), snapshot(reversal), now).ok, true);
const standard = newEvent("Normal LIVE");
standard.participants = [participant("A")];
standard.fish = [{ id: "f", name: "Blob", points: 1, enabled: true }];
const normalScore = structuredClone(standard);
normalScore.entries = [{ ...actualCatch, participantId: "A", id: "normal-catch" }];
assert.match(prepareSnapshot(snapshot(standard), snapshot(normalScore), now).error, /Draft/);
const modifiedType = { ...saved, historical: false };
assert.match(prepareSnapshot(snapshot(saved), snapshot(modifiedType), now).error, /tidak dapat diubah/i);
const verified = { ...saved, status: "finished", published: true, rosterLocked: true, historicalRecordedAt: new Date(now).toISOString(), timer: { durationSec: 5400, remainingSec: 0, runningSince: null } };
assert.equal(validArena(snapshot(verified)), true);
assert.equal(validateMatchTransition(snapshot(saved), snapshot(verified)) !== null, true, "normal snapshot cannot finalize historical draft");
assert.equal(validateMatchTransition(snapshot(verified), snapshot({ ...verified, entries: [] })) !== null, true, "final results remain locked");
const tied = structuredClone(verified);
tied.entries = [
  { ...officialAdjustment, id: "tie-a", participantId: "A", delta: 7 },
  { ...officialAdjustment, id: "tie-b", participantId: "B", delta: 7 },
  { ...officialAdjustment, id: "tie-c", participantId: "C", delta: 3 },
];
tied.historicalPodium = ["B", "A", "C"];
assert.equal(validArena(snapshot(tied)), true);
assert.deepEqual(standings(tied).map((r) => r.id), ["B", "A", "C"], "official tied podium preserves panitia's original ordering");
tied.historicalPodium = ["C", "A", "B"];
assert.deepEqual(standings(tied).map((r) => r.id), ["A", "B", "C"], "lower-scoring entity may not leapfrog higher scores");
const source = (rel) => fs.readFileSync(path.join(root, rel), "utf8");
assert.match(source("app/api/admin/historical/route.ts"), /isAdminAuthenticated/);
assert.match(source("app/api/admin/historical/route.ts"), /sameOrigin/);
