assert.match(source("lib/historical-server.ts"), /finishedAt: undefined/);
assert.match(source("components/admin/historical-entry-panel.tsx"), /Rekonsiliasi total poin resmi/);
assert.doesNotMatch(source("db/schema.sql"), /DROP TABLE|TRUNCATE TABLE/);
console.log("PASS: V3.1.1 historical Draft scoring, official reconciliation, no LIVE timer, 3-place validation, server-controlled timestamps, immutable audit, authenticated CAS finalization");
